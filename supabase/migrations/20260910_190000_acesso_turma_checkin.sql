create or replace function private.professor_da_turma(p_turma_id bigint)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.turma_professores tp
    join public.usuarios u on u.id = tp.usuario_id
    where tp.turma_id = p_turma_id
      and u.auth_id = (select auth.uid())
      and u.cargo = 'Professor'
      and u.status = 'Ativo'
  );
$$;

create or replace function public.validar_codigo_turma(p_codigo text)
returns table (turma_id bigint, turma_nome text, academia_nome text)
language sql stable security definer
set search_path = ''
as $$
  select t.id, t.nome, a.nome
  from public.turmas t
  join public.academias a on a.id = t.academia_id
  where upper(t.codigo_convite) = upper(trim(p_codigo))
    and a.status = 'Ativa'
  limit 1;
$$;

revoke all on function public.validar_codigo_turma(text) from public;
grant execute on function public.validar_codigo_turma(text) to anon, authenticated;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql security definer
set search_path = ''
as $$
declare
  v_academia_id bigint;
  v_nome text;
  v_cpf text;
  v_telefone text;
  v_codigo_turma text;
  v_turma_id bigint;
  v_aluno_id bigint;
begin
  v_nome := nullif(trim(coalesce(new.raw_user_meta_data ->> 'nome', '')), '');
  v_cpf := nullif(trim(coalesce(new.raw_user_meta_data ->> 'cpf', '')), '');
  v_telefone := nullif(trim(coalesce(new.raw_user_meta_data ->> 'telefone', '')), '');

  if new.invited_at is not null then
    begin
      v_academia_id := (new.raw_user_meta_data ->> 'academia_id')::bigint;
    exception when others then
      v_academia_id := null;
    end;

    if v_nome is null then
      v_nome := split_part(coalesce(new.email, 'Professor'), '@', 1);
    end if;

    if v_academia_id is null or not exists (
      select 1 from public.academias a
      where a.id = v_academia_id and a.status = 'Ativa'
    ) then
      raise exception 'Academia inválida para convite de professor';
    end if;

    insert into public.usuarios (
      auth_id, nome, email, cargo, telefone, cpf, status, academia_id, aluno_id
    )
    values (
      new.id, v_nome, lower(new.email), 'Professor', v_telefone, v_cpf,
      'Ativo', v_academia_id, null
    )
    on conflict (auth_id) do nothing;

    return new;
  end if;

  v_codigo_turma := nullif(trim(coalesce(new.raw_user_meta_data ->> 'codigo_turma', '')), '');

  if v_nome is null then raise exception 'Nome obrigatório para criar perfil'; end if;
  if v_codigo_turma is null then raise exception 'Código da turma obrigatório'; end if;

  select t.id, t.academia_id
  into v_turma_id, v_academia_id
  from public.turmas t
  join public.academias a on a.id = t.academia_id
  where upper(t.codigo_convite) = upper(v_codigo_turma)
    and a.status = 'Ativa'
  limit 1;

  if v_turma_id is null or v_academia_id is null then
    raise exception 'Código da turma inválido';
  end if;

  if v_cpf is not null then
    select a.id into v_aluno_id
    from public.alunos a
    where a.academia_id = v_academia_id
      and regexp_replace(coalesce(a.cpf, ''), '\D', '', 'g')
          = regexp_replace(v_cpf, '\D', '', 'g')
      and not exists (select 1 from public.usuarios u where u.aluno_id = a.id)
    limit 1;
  end if;

  if v_aluno_id is null then
    insert into public.alunos (
      nome, cpf, telefone, faixa, graus, categoria, status, academia_id
    )
    values (
      v_nome, v_cpf, v_telefone, 'Branca', 0, 'Adulto', 'Ativo', v_academia_id
    )
    returning id into v_aluno_id;
  else
    update public.alunos
    set nome = v_nome,
        cpf = coalesce(v_cpf, cpf),
        telefone = coalesce(v_telefone, telefone)
    where id = v_aluno_id;
  end if;

  insert into public.usuarios (
    auth_id, nome, email, cargo, telefone, cpf, status, academia_id, aluno_id
  )
  values (
    new.id, v_nome, lower(new.email), 'Aluno', v_telefone, v_cpf,
    'Ativo', v_academia_id, v_aluno_id
  )
  on conflict (auth_id) do nothing;

  insert into public.matriculas (aluno_id, turma_id)
  values (v_aluno_id, v_turma_id)
  on conflict (aluno_id, turma_id) do nothing;

  return new;
end;
$$;

create or replace function public.registrar_checkin(p_token text)
returns table (status text, mensagem text, turma_nome text, horario text)
language plpgsql security definer
set search_path = ''
as $$
declare
  v_aluno_id bigint;
  v_academia_id bigint;
  v_local_id bigint;
  v_horario_id bigint;
  v_turma_id bigint;
  v_turma_nome text;
  v_horario time;
  v_agora timestamp;
  v_data date;
  v_chamada_id bigint;
  v_inserido bigint;
begin
  if private.current_user_role() <> 'aluno' then
    raise exception 'Check-in disponível apenas para alunos' using errcode = '42501';
  end if;

  v_aluno_id := private.current_aluno_id();
  v_academia_id := private.current_academia_id();

  if v_aluno_id is null or v_academia_id is null then
    raise exception 'Perfil de aluno inválido' using errcode = '42501';
  end if;

  select l.id into v_local_id
  from public.locais l
  where l.token_qr::text = trim(p_token)
    and l.academia_id = v_academia_id
    and l.ativo = true
  limit 1;

  if v_local_id is null then
    return query select 'invalido'::text, 'QR Code inválido para sua academia.'::text, null::text, null::text;
    return;
  end if;

  v_agora := timezone('America/Sao_Paulo', now());
  v_data := v_agora::date;

  select h.id, t.id, t.nome, h.horario_inicio
  into v_horario_id, v_turma_id, v_turma_nome, v_horario
  from public.turma_horarios h
  join public.turmas t on t.id = h.turma_id
  join public.matriculas m on m.turma_id = t.id and m.aluno_id = v_aluno_id
  where t.local_id = v_local_id
    and extract(dow from v_agora)::smallint = h.dia_semana
    and v_agora between
      (v_data + h.horario_inicio - interval '15 minutes')
      and (v_data + h.horario_inicio + interval '60 minutes')
  order by abs(extract(epoch from (v_agora - (v_data + h.horario_inicio))))
  limit 1;

  if v_horario_id is null then
    return query select 'fora_da_janela'::text, 'Não há uma aula sua aberta para check-in neste local agora.'::text, null::text, null::text;
    return;
  end if;

  insert into public.checkins (aluno_id, turma_id, local_id, horario_id, aula_data)
  values (v_aluno_id, v_turma_id, v_local_id, v_horario_id, v_data)
  on conflict (aluno_id, horario_id, aula_data) do nothing
  returning id into v_inserido;

  if v_inserido is null then
    return query select 'ja_registrado'::text, 'Seu check-in desta aula já foi registrado.'::text, v_turma_nome, to_char(v_horario, 'HH24:MI');
    return;
  end if;

  insert into public.chamadas (turma_id, data, horario, professor, horario_id)
  values (v_turma_id, v_data, to_char(v_horario, 'HH24:MI'), 'Check-in', v_horario_id)
  on conflict (turma_id, data, horario_id) where horario_id is not null
  do update set horario = excluded.horario
  returning id into v_chamada_id;

  insert into public.presencas (chamada_id, aluno_id)
  values (v_chamada_id, v_aluno_id)
  on conflict (chamada_id, aluno_id) do nothing;

  return query select 'registrado'::text, 'Check-in realizado com sucesso.'::text, v_turma_nome, to_char(v_horario, 'HH24:MI');
end;
$$;

revoke all on function public.registrar_checkin(text) from public, anon;
grant execute on function public.registrar_checkin(text) to authenticated;

